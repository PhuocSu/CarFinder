export const PRICE_STEPS = [
  // 1,000,000 → 20,000,000 (step 1,000,000)
  ...Array.from({ length: 20 }, (_, i) => (i + 1) * 1_000_000),

  // 25,000,000 → 40,000,000 (step 5,000,000)
  25_000_000,
  30_000_000,
  35_000_000,
  40_000_000,

  // 50,000,000 → 100,000,000 (step 10,000,000)
  ...Array.from({ length: 6 }, (_, i) => (i + 5) * 10_000_000),
].map((value) => ({
  value,
  label: `${(value / 10_000).toLocaleString()} 만원`,
}));
